test('a learner can create a subject in a chosen learning level and teach its chapter and topic',()=>{
 render(<App/>);
 fireEvent.click(screen.getByRole('button',{name:'Try the local demo'}));
 fireEvent.change(screen.getByLabelText('Full name *'),{target:{value:'Asha'}});
 fireEvent.change(screen.getByLabelText('Country *'),{target:{value:'India'}});
 fireEvent.change(screen.getByLabelText('Preferred teaching language'),{target:{value:'en'}});
 fireEvent.click(screen.getByRole('button',{name:'Save and enter'}));
 fireEvent.click(screen.getByRole('button',{name:'Curriculum'}));
 fireEvent.change(document.getElementById('segment')!,{target:{value:'University'}});
 expect((screen.getAllByLabelText('Learning level')[1] as HTMLSelectElement).value).toBe('University');
 fireEvent.change(screen.getByLabelText('Your subject or course'),{target:{value:'Astrophysics'}});
 fireEvent.click(screen.getByRole('button',{name:/Plan my course/}));
 expect(screen.getByRole('heading',{name:'Astrophysics'})).toBeTruthy();
 expect((screen.getByLabelText('Your subject or course *') as HTMLInputElement).value).toBe('Astrophysics');
 fireEvent.change(screen.getByLabelText('Chapter *'),{target:{value:'Stars and galaxies'}});
 fireEvent.change(screen.getByLabelText('Topic *'),{target:{value:'Stellar evolution'}});
 fireEvent.change(screen.getByLabelText('Customize what you want to learn'),{target:{value:'Use visual examples'}});
 fireEvent.click(screen.getByRole('button',{name:/Continue to classroom/}));
 expect(JSON.parse(screen.getByTestId('course').textContent||'{}')).toEqual({title:'Astrophysics',segment:'University'});
 expect(JSON.parse(screen.getByTestId('plan').textContent||'{}')).toEqual({subject:'Astrophysics',chapter:'Stars and galaxies',topic:'Stellar evolution',requirements:'Use visual examples'});
});
